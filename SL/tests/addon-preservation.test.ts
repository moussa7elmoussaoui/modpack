async function collect(relative: string): Promise<void> {
  for (const entry of await readdir(path.join(repo, relative), { withFileTypes: true })) {
    const name = `${relative}/${entry.name}`;
    if (entry.isDirectory()) await collect(name);
    else if (entry.isFile()) original[name] = new Uint8Array(await readFile(path.join(repo, name)));
  }
}
