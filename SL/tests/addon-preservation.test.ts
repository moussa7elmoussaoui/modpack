const json = (archive: Archive, name: string): JsonObject => JSON.parse(strFromU8(archive[name]));
function uuidFactory(): () => string {
  let sequence = 0;
  return () => `12345678-1234-4234-8234-${String(++sequence).padStart(12, '0')}`;
}
function assertOriginalBytes(actual: Archive, expected: Archive): void {
  assert.deepEqual(Object.keys(actual).sort(), Object.keys(expected).sort(), 'cleanup must leave exactly the original files');
  for (const [name, bytes] of Object.entries(expected)) {
    assert.deepEqual(actual[name], bytes, `${name}: every original byte must survive UUID and registration cleanup`);
  }
}

// This cleanup deliberately does not import the production JSON editor, nor
// parse/stringify any file back to text. It removes only known generated text.
function removeExact(source: string, inserted: string, expectedCount: number): string {
  assert.equal(source.split(inserted).length - 1, expectedCount, `expected ${expectedCount} insertion(s) of ${inserted.slice(0, 90)}`);
  return source.split(inserted).join('');
}
function verifyAndRestoreUuids(generated: Archive, reference: Archive): void {
  const replacements = new Map<string, string>();
  const before = MANIFESTS.map(name => json(reference, name));
  const after = MANIFESTS.map(name => json(generated, name));
  for (let pack = 0; pack < before.length; pack++) {
    const previous = [before[pack].header, ...before[pack].modules];
    const next = [after[pack].header, ...after[pack].modules];
    assert.equal(next.length, previous.length);
    for (const [index, part] of next.entries()) {
      assert.match(part.uuid, /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i);
      replacements.set(previous[index].uuid, part.uuid);
    }
  }
  assert.equal(new Set(replacements.values()).size, replacements.size, 'all fresh identifiers must be distinct');
  for (const id of replacements.values()) assert.equal(replacements.has(id), false, 'fresh identifiers must differ from all original identifiers');
  for (let pack = 0; pack < before.length; pack++) {
    const expected = structuredClone(before[pack]);
    expected.header.uuid = replacements.get(expected.header.uuid);
    for (const module of expected.modules) module.uuid = replacements.get(module.uuid);
    for (const dependency of expected.dependencies ?? []) {
      if (replacements.has(dependency.uuid)) dependency.uuid = replacements.get(dependency.uuid);
    }
    assert.deepEqual(after[pack], expected, 'all manifest data outside the required UUID fields must remain unchanged');
    let source = strFromU8(generated[MANIFESTS[pack]]);
    for (const [previous, next] of replacements) source = source.split(JSON.stringify(next)).join(JSON.stringify(previous));
    generated[MANIFESTS[pack]] = strToU8(source);
  }
}

interface AddedSkin {
  name: string;
  model: number;
  texture: string;
  icon: string;
}
function verifyAndRemoveSkins(generated: Archive, reference: Archive, skins: SkinInput[]): void {
  let source = strFromU8(generated[SCRIPT]);
  const block = /\/\/ Generated by SkinLink\. Existing bundled indices and the random pool are preserved\.\r?\nconst SKINLINK_SKINS = ([^\r\n]+);\r?\nconst SKINLINK_NAME_INDICES = ([^\r\n]+);\r?\n\r?\n/g;
  const declarations = [...source.matchAll(block)];
  assert.equal(declarations.length, 1);
  const additions: AddedSkin[] = JSON.parse(declarations[0][1]);
  const names: [string, number][] = JSON.parse(declarations[0][2]);
  const firstIndex = Object.keys(json(reference, CLIENT)['minecraft:client_entity'].description.textures)
    .filter(name => /^player_\d+$/.test(name)).length;
  assert.deepEqual(names, skins.map((skin, index) => [skin.names[0], firstIndex + index]));
  assert.deepEqual(additions, skins.map(skin => ({
    name: skin.names[0], model: skin.model === 'slim' ? 1 : 0,
    texture: `player/generated/${skin.model}/${skin.names[0].toLowerCase()}`,
    icon: `player/generated/${skin.model}/${skin.names[0].toLowerCase()}`,
  })));

  const expectedClient = json(reference, CLIENT);
  const expectedControllers = json(reference, CONTROLLERS);
  const expectedEntity = json(reference, ENTITY);
  const addedAliases: string[] = [], addedReferences: string[] = [];
  for (const [index, skin] of additions.entries()) {
    const texturePath = `RP/textures/entity/${skin.texture}.png`;
    const iconPath = `RP/textures/morph_icons/minecraft/${skin.icon}.png`;
    assert.equal(Object.hasOwn(reference, texturePath), false);
    assert.equal(Object.hasOwn(reference, iconPath), false);
    assert.deepEqual(generated[texturePath], skins[index].texturePng);
    assert.deepEqual(generated[iconPath], skins[index].iconPng);
    delete generated[texturePath]; delete generated[iconPath];
    const alias = `player_${firstIndex + index}`;
    const value = `textures/entity/${skin.texture}`;
    expectedClient['minecraft:client_entity'].description.textures[alias] = value;
    addedAliases.push(`${JSON.stringify(alias)}:${JSON.stringify(value)}`);
    const referenceName = `Texture.${alias}`;
    addedReferences.push(JSON.stringify(referenceName));
    for (const controller of Object.values(expectedControllers.render_controllers) as JsonObject[]) {
      controller.arrays.textures['Array.textures'].push(referenceName);
    }
  }
  const originalMaximum = expectedEntity['minecraft:entity'].description.properties['dark7mc:player_skin'].range[1];
  expectedEntity['minecraft:entity'].description.properties['dark7mc:player_skin'].range[1] += skins.length;
  assert.deepEqual(json(generated, CLIENT), expectedClient, 'texture aliases must be the only client entity changes');
  assert.deepEqual(json(generated, CONTROLLERS), expectedControllers, 'appended texture references must be the only render controller changes');
  assert.deepEqual(json(generated, ENTITY), expectedEntity, 'the skin range endpoint must be the only behavior entity change');

  generated[CLIENT] = strToU8(removeExact(strFromU8(generated[CLIENT]), `,${addedAliases.join(',')}`, 1));
  const controllerCount = Object.keys(expectedControllers.render_controllers).length;
  generated[CONTROLLERS] = strToU8(removeExact(strFromU8(generated[CONTROLLERS]), `,${addedReferences.join(',')}`, controllerCount));
  const rangePattern = /("dark7mc:player_skin"\s*:\s*\{[^{}]*?"range"\s*:\s*\[\s*0\s*,\s*)(\d+)(\s*\])/g;
  const entityText = strFromU8(generated[ENTITY]);
  assert.equal([...entityText.matchAll(rangePattern)].length, 1);
  generated[ENTITY] = strToU8(entityText.replace(rangePattern, (_all, prefix: string, value: string, suffix: string) => {
    assert.equal(Number(value), originalMaximum + skins.length);
    return `${prefix}${originalMaximum}${suffix}`;
  }));

  source = source.replace(block, '');
  const originalScript = strFromU8(reference[SCRIPT]);
  const newline = originalScript.match(/\r\n|\n/)![0];
  for (const [pattern, expression] of [
    [/export const playerSkins = Object\.freeze\(\[([\s\S]*?)\]\);/, 'SKINLINK_SKINS'],
    [/const PLAYER_SKIN_BY_NAME = Object\.freeze\(Object\.fromEntries\(\[([\s\S]*?)\]\)\);/, 'SKINLINK_NAME_INDICES'],
  ] as const) {
    const originalBody = originalScript.match(pattern)![1];
    const addedComma = originalBody.trimEnd().endsWith(',') ? '' : ',';
    source = removeExact(source, `${addedComma}${newline}  ...${expression}`, 1);
  }
  assert.equal(source.includes('SKINLINK_'), false);
  generated[SCRIPT] = strToU8(source);
}

function alternateFormatting(): Archive {
  const reference = { ...original };
  const existingUuid = json(original, MANIFESTS[0]).header.uuid;
  // An unrelated matching UUID and precise original number/string spellings
  // expose global replacements and whole-document JSON serialization.
  const probe = `\n\t"preservation_probe":{"uuid":${JSON.stringify(existingUuid)},"n":6.0,"tiny":1e-7,"large":90071992547409931234567890123456789,"escaped":"\\u0061\\/b"},`;
  for (const name of JSON_FILES) {
    const source = strFromU8(original[name]).replace(/\r\n/g, '\n');
    reference[name] = strToU8(source.replace('{', `{${probe}`) + ' \t\n\n');
  }
  let script = strFromU8(original[SCRIPT]).replace(/\r\n/g, '\n');
  for (const pattern of [/(export const playerSkins = Object\.freeze\(\[[\s\S]*?)(\]\);)/, /(const PLAYER_SKIN_BY_NAME = Object\.freeze\(Object\.fromEntries\(\[[\s\S]*?)(\]\)\);)/]) {
    script = script.replace(pattern, (_all, prefix: string, suffix: string) => {
      const end = prefix.trimEnd().length;
      return `${prefix.slice(0, end)},${prefix.slice(end)}\t \n\n${suffix}`;
    });
  }
  reference[SCRIPT] = strToU8(script + ' \t\n');
  return reference;
}

async function realSkinInputs(): Promise<SkinInput[]> {
  const template = new Uint8Array(await readFile(new URL('../public/assets/icon-templates.json', import.meta.url)));
  const originalFetch = globalThis.fetch;
  globalThis.fetch = async input => {
    assert.equal(input, '/assets/icon-templates.json');
    return new Response(template, { headers: { 'content-type': 'application/json' } });
  };
  try {
    const skins: SkinInput[] = [];
    for (const [index, [model, sourceName, name]] of SAMPLE_SKINS.entries()) {
      const texture = original[`RP/textures/entity/player/${model}/${sourceName}.png`];
      const decoded = await decodeSkin(new File([new Uint8Array(texture)], 'uploaded.png', { type: 'image/png' }));
      URL.revokeObjectURL(decoded.iconUrl);
      assert.equal(decoded.model, model);
      assert.deepEqual(decoded.texturePng, texture);
      skins.push({ id: `preserve_${index}`, names: [name], model, texturePng: decoded.texturePng, iconPng: decoded.iconPng });
    }
    return skins;
  } finally { globalThis.fetch = originalFetch; }
}

test('empty website exports recover every original file byte after restoring only UUID tokens', async t => {
  assertOriginalBytes(unzipSync(preparedBase), original);
  for (const [label, reference, base] of [
    ['root files and prepared website base', original, preparedBase],
    ['LF, extra whitespace, trailing commas, precise numbers, escaped strings, and unrelated UUIDs', alternateFormatting(), undefined],
  ] as const) {
    await t.test(label, async () => {
      const generated = unzipSync(await generateAddon(base ?? zipSync(reference, { level: 0 }), [], { uuid: uuidFactory() }));
      verifyAndRestoreUuids(generated, reference);
      assertOriginalBytes(generated, reference);
    });
  }
});

test('exports with real Wide and Slim skins recover every original file byte after precise cleanup', async t => {
  const skins = await realSkinInputs();
  for (const [label, reference, base] of [
    ['root files and prepared website base', original, preparedBase],
    ['LF, extra whitespace, trailing commas, precise numbers, escaped strings, and unrelated UUIDs', alternateFormatting(), undefined],
  ] as const) {
    await t.test(label, async () => {
      const generated = unzipSync(await generateAddon(base ?? zipSync(reference, { level: 0 }), skins, { uuid: uuidFactory() }));
      assert.equal(Object.keys(generated).length, Object.keys(reference).length + skins.length * 2);
      verifyAndRestoreUuids(generated, reference);
      verifyAndRemoveSkins(generated, reference, skins);
      assertOriginalBytes(generated, reference);
    });
  }
});

// This exercises the actual page download handler in a DOM environment. It is
// not a browser test: local assets replace HTTP, and Blob downloads stay in memory.
test('the real workbench download controls preserve all original file bytes with and without uploaded skins', async () => {
  const expectedSkins = await realSkinInputs();
  const assets = new Map<string, Uint8Array>();
  for (const name of ['base-addon.zip', 'base-info.json', 'icon-templates.json']) {
    assets.set(`/assets/${name}`, new Uint8Array(await readFile(new URL(`../public/assets/${name}`, import.meta.url))));
  }
  const localFetch: typeof fetch = async input => {
    const url = new URL(String(input), 'http://skinlink.test/');
    assert.equal(url.origin, 'http://skinlink.test');
    const bytes = assets.get(url.pathname);
    assert.ok(bytes, `unexpected asset request: ${url.pathname}`);
    return new Response(new Uint8Array(bytes), { headers: { 'content-type': url.pathname.endsWith('.json') ? 'application/json' : 'application/zip' } });
  };
  const dom = new DOMWindow({ url: 'http://skinlink.test/' });
  const document = dom.document as unknown as Document;
  document.head.innerHTML = '<meta name="theme-color" content="#f2f4f5">';
  document.body.innerHTML = '<div id="app"></div>';
  const globals: Record<string, unknown> = {
    window: dom, document,
    HTMLElement: dom.HTMLElement, HTMLInputElement: dom.HTMLInputElement,
    HTMLTextAreaElement: dom.HTMLTextAreaElement, Element: dom.Element, Node: dom.Node,
  };
  const previousGlobals = new Map(Object.keys(globals).map(name => [name, Object.getOwnPropertyDescriptor(globalThis, name)]));
  const originalFetch = globalThis.fetch;
  const originalClick = dom.HTMLAnchorElement.prototype.click;
  const downloadUrls: string[] = [];
  const downloads: { filename: string; bytes: Promise<Uint8Array> }[] = [];
  let cleanup: (() => void) | undefined;
  const query = <T extends Element = HTMLElement>(selector: string, scope: ParentNode = document): T => {
    const found = scope.querySelector<T>(selector); assert.ok(found, selector); return found;
  };
  async function waitFor(predicate: () => boolean, label: string): Promise<void> {
    const deadline = Date.now() + 30000;
    while (!predicate()) {
      if (Date.now() > deadline) throw new Error(`Timed out waiting for ${label}: ${document.querySelector('#export-feedback')?.textContent}`);
      await new Promise<void>(resolve => setTimeout(resolve, 10));
    }
  }
  async function downloadAddon(): Promise<Archive> {
    const next = downloads.length + 1;
    assert.equal(query<HTMLDialogElement>('#skin-dialog').open, false, 'downloads start from the skin list');
    const button = query<HTMLButtonElement>('#generate');
    assert.equal(button.disabled, false);
    button.click();
    await waitFor(() => downloads.length === next && !button.classList.contains('is-busy'), 'the addon download');
    assert.equal(downloads[next - 1].filename, 'modpack.mcaddon');
    return unzipSync(await downloads[next - 1].bytes);
  }
  try {
    for (const [name, value] of Object.entries(globals)) Object.defineProperty(globalThis, name, { configurable: true, writable: true, value });
    globalThis.fetch = localFetch;
    dom.HTMLAnchorElement.prototype.click = function () {
      const anchor = this as unknown as HTMLAnchorElement;
      assert.equal(anchor.id, 'download-again');
      assert.match(anchor.href, /^blob:/);
      downloadUrls.push(anchor.href);
      downloads.push({ filename: anchor.download, bytes: originalFetch(anchor.href).then(response => response.arrayBuffer()).then(bytes => new Uint8Array(bytes)) });
    };
    // All image decoding and packaging services are the unmodified production implementations.
    cleanup = mountWorkbench(query('#app'), { assetRoot: '/', fetch: localFetch });
    await waitFor(() => !query<HTMLButtonElement>('#generate').disabled, 'the actual base assets');
    const empty = await downloadAddon();
    verifyAndRestoreUuids(empty, original);
    assertOriginalBytes(empty, original);

    for (const [index, [model, sourceName, name]] of SAMPLE_SKINS.entries()) {
      query<HTMLButtonElement>('#add-skin').click();
      assert.equal(query<HTMLDialogElement>('#skin-dialog').open, true);
      const editor = query<HTMLElement>('.skin-editor:not([hidden])');
      const names = query<HTMLInputElement>('input[type="text"]', editor);
      names.value = name; names.dispatchEvent(new dom.Event('input', { bubbles: true }) as unknown as Event);
      const upload = query<HTMLInputElement>('input[type="file"]', editor);
      const texture = original[`RP/textures/entity/player/${model}/${sourceName}.png`];
      const file = new File([new Uint8Array(texture)], `uploaded_${index}.png`, { type: 'image/png' });
      Object.defineProperty(upload, 'files', { configurable: true, value: [file] });
      upload.dispatchEvent(new dom.Event('change', { bubbles: true }) as unknown as Event);
      await waitFor(() => !query<HTMLButtonElement>('.commit-skin', editor).disabled, `decoding and validating ${name}`);
      assert.equal(query('.model-summary', editor).textContent?.trim(), `${model === 'wide' ? 'Wide' : 'Slim'} · Automatically selected`);
      assert.equal(editor.querySelector('input[type="radio"]'), null);
      query<HTMLButtonElement>('.commit-skin', editor).click();
      assert.equal(document.querySelectorAll('#skin-list .edit-skin').length, index + 1);
      assert.equal(query('#skin-dialog').classList.contains('is-closing'), true, 'the popup remains mounted for its exit animation');
      await waitFor(() => !query<HTMLDialogElement>('#skin-dialog').open, 'closing the skin editor');
    }
    const customized = await downloadAddon();
    verifyAndRestoreUuids(customized, original);
    verifyAndRemoveSkins(customized, original, expectedSkins);
    assertOriginalBytes(customized, original);
    assert.equal(downloads.length, 2);
  } finally {
    cleanup?.();
    for (const url of downloadUrls) URL.revokeObjectURL(url);
    dom.HTMLAnchorElement.prototype.click = originalClick;
    globalThis.fetch = originalFetch;
    for (const [name, descriptor] of previousGlobals) {
      if (descriptor) Object.defineProperty(globalThis, name, descriptor);
      else Reflect.deleteProperty(globalThis, name);
    }
    await dom.happyDOM.abort();
  }
});
