import { strFromU8, strToU8, unzip, zip } from 'fflate';
import { readPngDimensions, validateAssignments, validateSkinDimensions } from './validation';
import { readReservedPlayerNames } from './name-policy';
import { allocatePlayerAssetPaths } from './player-assets';

export type SkinModel = 'wide' | 'slim';

export interface SkinInput {
  id: string;
  /** Exactly one player name per list item; enforced again before packaging. */
  names: string[];
  model: SkinModel;
  texturePng: Uint8Array;
  iconPng: Uint8Array;
}

export interface AddonOptions {
  uuid?: () => string;
}

type JsonObject = Record<string, any>;
type Archive = Record<string, Uint8Array>;

const SCRIPT_PATH = 'BP/scripts/data/player-skins.js';
const CLIENT_PATH = 'RP/entity/player.entity.json';
const CONTROLLERS_PATH = 'RP/render_controllers/player.morph.render_controllers.json';
const ENTITY_PATH = 'BP/entities/player.json';
const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

function unpack(base: Uint8Array): Promise<Archive> {
  return new Promise((resolve, reject) => {
    unzip(base, (error, files) => {
      if (error) reject(new Error('The bundled base addon could not be read. Run the asset preparation command again.'));
      else resolve(files);
    });
  });
}

function pack(files: Archive): Promise<Uint8Array> {
  return new Promise((resolve, reject) => {
    zip(files, { level: 6 }, (error, data) => {
      if (error) reject(new Error(`The addon could not be packaged: ${error.message}`));
      else resolve(data);
    });
  });
}

function readText(files: Archive, path: string): string {
  if (!(files[path] instanceof Uint8Array)) throw new Error(`The base addon is missing ${path}.`);
  return strFromU8(files[path]);
}

function readJson(files: Archive, path: string): JsonObject {
  try {
    const value = JSON.parse(readText(files, path));
    if (!value || Array.isArray(value) || typeof value !== 'object') throw new Error('Expected a JSON object.');
    return value;
  } catch (error) {
    throw new Error(`Could not read ${path}: ${(error as Error).message}`);
  }
}

function writeJson(files: Archive, path: string, value: JsonObject): void {
  files[path] = strToU8(`${JSON.stringify(value, null, 2)}\n`);
}

function assertTemplate(condition: unknown, detail: string): asserts condition {
  if (!condition) throw new Error(`The bundled addon template is incompatible (${detail}). Refresh the base assets before generating.`);
}

function sourceJson(value: unknown): string {
  return JSON.stringify(value).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

function appendToArrayBody(body: string, expression: string): string {
  const trimmed = body.trimEnd();
  return `${trimmed}${trimmed.endsWith(',') ? '' : ','}\n  ...${expression}\n`;
}

function extendSkinScript(source: string, skins: SkinInput[], firstIndex: number, assetPaths: string[]): string {
  assertTemplate(!source.includes('const SKINLINK_SKINS ='), 'base already contains generated SkinLink entries');
  const exportedArray = /export const playerSkins = Object\.freeze\(\[([\s\S]*?)\]\);/g;
  const namedArray = /const PLAYER_SKIN_BY_NAME = Object\.freeze\(Object\.fromEntries\(\[([\s\S]*?)\]\)\);/g;
  assertTemplate([...source.matchAll(exportedArray)].length === 1, 'playerSkins declaration');
  assertTemplate([...source.matchAll(namedArray)].length === 1, 'player name mapping declaration');

  const entries = skins.map((skin, index) => ({
    name: skin.names[0],
    model: skin.model === 'slim' ? 1 : 0,
    texture: assetPaths[index],
    icon: assetPaths[index],
  }));
  const names = skins.map((skin, index) => [skin.names[0], firstIndex + index]);
  const declarations = `// Generated by SkinLink. Existing bundled indices and the random pool are preserved.\nconst SKINLINK_SKINS = ${sourceJson(entries)};\nconst SKINLINK_NAME_INDICES = ${sourceJson(names)};\n\n`;

  return source
    .replace(exportedArray, (_match, body: string) => `${declarations}export const playerSkins = Object.freeze([${appendToArrayBody(body, 'SKINLINK_SKINS')}]);`)
    .replace(namedArray, (_match, body: string) => `const PLAYER_SKIN_BY_NAME = Object.freeze(Object.fromEntries([${appendToArrayBody(body, 'SKINLINK_NAME_INDICES')}]));`);
}

function refreshManifests(files: Archive, uuid: () => string): void {
  const paths = ['BP/manifest.json', 'RP/manifest.json'];
  const manifests = paths.map((path) => readJson(files, path));
  const replacements = new Map<string, string>();
  const generatedIds = new Set<string>();
  const nextUuid = (): string => {
    const value = uuid();
    if (!UUID_PATTERN.test(value) || generatedIds.has(value)) throw new Error('Could not create unique pack identifiers. Please try generating again.');
    generatedIds.add(value);
    return value;
  };

  manifests.forEach((manifest) => {
    assertTemplate(typeof manifest.header?.uuid === 'string' && Array.isArray(manifest.header.version), 'manifest header');
    assertTemplate(Array.isArray(manifest.modules) && manifest.modules.length > 0, 'manifest modules');
    [manifest.header, ...manifest.modules].forEach((part: JsonObject) => {
      assertTemplate(typeof part.uuid === 'string' && !replacements.has(part.uuid), 'duplicate or missing original pack identifier');
      replacements.set(part.uuid, nextUuid());
    });
  });

  manifests.forEach((manifest, index) => {
    manifest.header.uuid = replacements.get(manifest.header.uuid);
    manifest.modules.forEach((module: JsonObject) => { module.uuid = replacements.get(module.uuid); });
    if (Array.isArray(manifest.dependencies)) {
      manifest.dependencies.forEach((dependency: JsonObject) => {
        if (typeof dependency.uuid === 'string' && replacements.has(dependency.uuid)) {
          dependency.uuid = replacements.get(dependency.uuid);
        }
      });
    }
    writeJson(files, paths[index], manifest);
  });
}

/** Generates an independent addon in memory. The source BP/RP files are never written. */
export async function generateAddon(
  base: Uint8Array,
  skins: SkinInput[],
  options: AddonOptions = {},
  onProgress?: (message: string) => void,
): Promise<Uint8Array> {
  const errors = skins.length ? validateAssignments(skins) : [];
  if (errors.length) throw new Error(errors.join('\n'));

  for (const skin of skins) {
    const texture = readPngDimensions(skin.texturePng);
    validateSkinDimensions(texture.width, texture.height);
    if (texture.width !== texture.height) throw new Error('Convert legacy skins to 64×64 before packaging the addon.');
    const icon = readPngDimensions(skin.iconPng);
    if (icon.width !== 128 || icon.height !== 128) throw new Error('Generated skin icons must be exactly 128×128 pixels.');
  }

  onProgress?.('Reading the base addon…');
  const files = await unpack(base);
  if (skins.length === 0) {
    refreshManifests(files, options.uuid ?? (() => crypto.randomUUID()));
    onProgress?.('Packaging your .mcaddon…');
    return pack(files);
  }
  const client = readJson(files, CLIENT_PATH);
  const controllers = readJson(files, CONTROLLERS_PATH);
  const entity = readJson(files, ENTITY_PATH);
  const script = readText(files, SCRIPT_PATH);
  const reservedErrors = validateAssignments(skins, readReservedPlayerNames(script));
  if (reservedErrors.length) throw new Error(reservedErrors.join('\n'));
  const textures = client['minecraft:client_entity']?.description?.textures;
  assertTemplate(textures && typeof textures === 'object', 'client texture aliases');
  const existingIndices = Object.keys(textures).filter((key) => /^player_\d+$/.test(key)).map((key) => Number(key.slice(7))).sort((a, b) => a - b);
  const firstIndex = existingIndices.length;
  assertTemplate(firstIndex > 0 && existingIndices.every((value, index) => value === index), 'non-contiguous bundled skin indices');

  const textureArrays = Object.values(controllers.render_controllers ?? {}).map((controller: any) => controller.arrays?.textures?.['Array.textures']);
  assertTemplate(textureArrays.length === 4, 'expected four player render controllers');
  textureArrays.forEach((array) => {
    assertTemplate(Array.isArray(array) && array.length === firstIndex && array.every((value, index) => value === `Texture.player_${index}`), 'render-controller texture ordering');
  });
  const skinProperty = entity['minecraft:entity']?.description?.properties?.['dark7mc:player_skin'];
  assertTemplate(skinProperty?.type === 'int' && Array.isArray(skinProperty.range) && skinProperty.range[0] === 0 && skinProperty.range[1] === firstIndex - 1, 'skin property range');

  onProgress?.('Adding skins, icons, and player names…');
  const assetPaths = allocatePlayerAssetPaths(skins, Object.keys(files));
  skins.forEach((skin, index) => {
    const path = assetPaths[index];
    const texturePath = `RP/textures/entity/${path}.png`;
    const iconPath = `RP/textures/morph_icons/minecraft/${path}.png`;
    assertTemplate(!files[texturePath] && !files[iconPath], 'custom skin filename collision');
    files[texturePath] = skin.texturePng;
    files[iconPath] = skin.iconPng;
    textures[`player_${firstIndex + index}`] = `textures/entity/${path}`;
    textureArrays.forEach((array) => array.push(`Texture.player_${firstIndex + index}`));
  });
  skinProperty.range[1] = firstIndex + skins.length - 1;
  writeJson(files, CLIENT_PATH, client);
  writeJson(files, CONTROLLERS_PATH, controllers);
  writeJson(files, ENTITY_PATH, entity);
  files[SCRIPT_PATH] = strToU8(extendSkinScript(script, skins, firstIndex, assetPaths));
  refreshManifests(files, options.uuid ?? (() => crypto.randomUUID()));
  onProgress?.('Packaging your .mcaddon…');
  return pack(files);
}
